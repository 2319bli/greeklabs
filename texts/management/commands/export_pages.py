"""Export the existing app and validated catalogue for static hosting."""
import json
import shutil
import tempfile
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from django.template.loader import render_to_string
from django.test.utils import override_settings

from texts.catalog import ContentError, load_catalog


class Command(BaseCommand):
    help = "Build a self-contained GitHub Pages site (default: _site/)."

    def add_arguments(self, parser):
        parser.add_argument("--output", type=Path, default=settings.BASE_DIR / "_site")

    def handle(self, *args, **options):
        output = options["output"].resolve()
        root = Path(settings.BASE_DIR).resolve()
        marker = ".greeklabs-export"
        sources = [root / name for name in ("static", "templates", "data")]
        if output == root or output in root.parents or any(
            source == output or source in output.parents or output in source.parents
            for source in sources
        ):
            raise CommandError("Export directory must be separate from the source files.")
        if output.exists() and (
            not output.is_dir()
            or (any(output.iterdir()) and not (output / marker).is_file())
        ):
            raise CommandError("Refusing to replace an existing directory without a GreekLabs export marker.")
        try:
            catalogue = load_catalog()
        except ContentError as exc:
            raise CommandError(str(exc)) from exc

        # All URLs are relative, so account sites, project sites and local previews work.
        with override_settings(STORAGES={
            **settings.STORAGES,
            "staticfiles": {
                "BACKEND": "django.contrib.staticfiles.storage.StaticFilesStorage",
                "OPTIONS": {"base_url": "./static/"},
            },
        }):
            html = render_to_string("revision/index.html", {"catalog_url": "./data/catalog.json"})

        output.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix=".greeklabs-build-", dir=output.parent) as temp:
            build = Path(temp) / "site"
            (build / "data").mkdir(parents=True)
            (build / "index.html").write_text(html, encoding="utf-8")
            (build / "data/catalog.json").write_text(
                json.dumps(catalogue, ensure_ascii=False, separators=(",", ":")) + "\n",
                encoding="utf-8",
            )
            asset_types = {".js", ".css", ".svg", ".png", ".jpg", ".jpeg", ".webp", ".ico", ".woff", ".woff2"}
            for source in (root / "static").rglob("*"):
                relative = source.relative_to(root / "static")
                if source.is_symlink():
                    raise CommandError("Static assets must not contain symbolic links.")
                if not source.is_file() or source.suffix not in asset_types or any(p.startswith(".") for p in relative.parts):
                    continue
                target = build / "static" / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, target)
            (build / ".nojekyll").touch()
            (build / marker).write_text("Generated by manage.py export_pages. Safe to rebuild.\n", encoding="utf-8")
            # Validate and render everything before replacing a previous generated build.
            if output.exists():
                shutil.rmtree(output)
            build.rename(output)
        self.stdout.write(self.style.SUCCESS(f"Exported GreekLabs to {output}"))
